    /// <summary>Returns the given stage (0-based) as a 20x10 board of CellType values.</summary>
    public static int[,] Get(int stage)
    {
        stage %= Count;
        int h = Raw.GetLength(1), w = Raw.GetLength(2);
        var board = new int[h, w];
        for (int r = 0; r < h; r++)
            for (int c = 0; c < w; c++)
                board[r, c] = Raw[stage, r, c] switch
                {
                    1 => CellType.Wall,
                    2 => CellType.Gem,
                    _ => CellType.Empty,
                };
        return board;
    }
